while cap.isOpened():
    ret, frame = cap.read()
    if not ret:
        break

    results = model.track(frame, persist=True, tracker="bytetrack.yaml")[0]
    output_frame = frame.copy()

    if results.boxes.id is not None:
        ids = results.boxes.id.cpu().numpy()
        boxes = results.boxes.xyxy.cpu().numpy()
        class_ids = results.boxes.cls.cpu().numpy()

        for box, track_id, cls in zip(boxes, ids, class_ids):
            x1, y1, x2, y2 = map(int, box)
            cls = int(cls)
            track_id = int(track_id)

            color = get_color_by_class(cls)

            # Label by class
            if cls == 0:
                label = f"ID: {track_id} - Team A"
            elif cls == 1:
                label = f"ID: {track_id} - Team B"
            elif cls == 2:
                label = f"ID: {track_id} - Coach"
            elif cls == 3:
                label = f"ID: {track_id} - Referee"
            elif cls == 4:
                label = f"ID: {track_id} - Hoop"
            elif cls == 5:
                label = f"ID: {track_id} - Ball"
            else:
                label = f"ID: {track_id} - Class {cls}"

            cv2.rectangle(output_frame, (x1, y1), (x2, y2), color, 2)
            cv2.putText(output_frame, label, (x1, y1 - 10),
                        cv2.FONT_HERSHEY_SIMPLEX, 0.6, color, 2)

