class PlayerTracker:
    def __init__(self):
        self.features_db = defaultdict(dict)  # {class_id: {static_id: feature}}
        self.assigned_ids = {}  # {yolo_track_id: static_id}
        self.positions = defaultdict(dict)  # {frame_count: {static_id: position}}
        self.player_history = defaultdict(lambda: deque(maxlen=20))  # Longer history
