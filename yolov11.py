def generate_heatmap_with_full_colorbar(position_data, team_name, hoop_positions, output_filename, img_width, img_height, colormap):
    if not position_data:
        print(f"No position data for {team_name} to generate heatmap. Skipping.")
        return

    x_coords = [p[0] for p in position_data]
    y_coords = [p[1] for p in position_data]

    # Set up figure: extend width for indicator bar
    fig, ax = plt.subplots(figsize=(img_width/100 + 1.75, img_height/100), dpi=100)
    ax.set_facecolor('#232c31')
    fig.patch.set_facecolor('#232c31')

    # Main KDE heatmap
    sns.kdeplot(
        x=x_coords,
        y=y_coords,
        cmap=colormap,
        fill=True,
        levels=50,
        alpha=0.95,
        thresh=0,
        ax=ax,
        cbar=False
    )

    # Draw hoops as black hollow circles
    for hoop_pos in hoop_positions:
        ax.scatter(
            hoop_pos[0], hoop_pos[1],
            s=400,
            facecolors='none',
            edgecolors='black',
            linewidths=3,
            marker='o',
            zorder=5
        )

    ax.axis('off')
    ax.set_xlim(0, img_width)
    ax.set_ylim(img_height, 0)
    ax.set_aspect('equal', adjustable='box')

    # Add colorbar as indicator (with full set of labels)
    from mpl_toolkits.axes_grid1 import make_axes_locatable
    divider = make_axes_locatable(ax)
    cax = divider.append_axes("right", size="3.5%", pad=0.10)

    # Dummy mappable for the colorbar
    mappable = plt.cm.ScalarMappable(cmap=colormap)
    mappable.set_array([])

    cbar = plt.colorbar(mappable, cax=cax)
    cbar.set_label('Coverage', color='white')
    labels = ['least covered', 'less covered', 'average covered', 'more covered', 'most covered']
    ticks = [0.0, 0.25, 0.5, 0.75, 1.0]
    cbar.set_ticks(ticks)
    cbar.set_ticklabels(labels)
    cbar.ax.tick_params(colors='white')
    cbar.outline.set_edgecolor('white')
    cbar.ax.yaxis.label.set_color('white')

    plt.savefig(output_filename, bbox_inches='tight', pad_inches=0.1, facecolor=fig.get_facecolor())
    plt.close()
    print(f"✅ Heatmap with full colorbar for {team_name} saved as '{output_filename}'.")

