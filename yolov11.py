class StablePlayerTracker:
    def __init__(self):
        # Store multiple features per player for better matching
        self.feature_db = defaultdict(lambda: deque(maxlen=5))  # Last 5 features per player
        self.assigned_ids = {}  # {yolo_track_id: static_id}
        self.player_history = defaultdict(lambda: deque(maxlen=30))  # Position history
        self.position_data = defaultdict(list)  # For heatmaps
        self.speed_data = defaultdict(list)     # For analytics

        # ID management
        self.available_ids = {
            TEAM_A['class_id']: deque(TEAM_A['id_range']),
            TEAM_B['class_id']: deque(TEAM_B['id_range'])
        }
        self.last_seen = {}  # {static_id: last_frame_seen}
        self.current_frame = 0

        # Tracking parameters
        self.similarity_threshold = 0.92  # Higher threshold for stable IDs
        self.max_frames_missing = 60  # Longer period before ID recycling
        self.min_features = 3  # Minimum features before using average

    def get_avg_feature(self, static_id, cls):
        """Get average feature vector for a player"""
        features = list(self.feature_db[(cls, static_id)])
        if len(features) >= self.min_features:
            return np.mean(features, axis=0)
        elif features:
            return features[-1]
        return None

    def assign_id(self, track_id, cls, crop):
        self.current_frame += 1

        # Reuse existing ID if available
        if track_id in self.assigned_ids:
            static_id = self.assigned_ids[track_id]
            self.last_seen[static_id] = self.current_frame

            # Update feature database
            feature = extract_features(crop, reid_model, device)
            self.feature_db[(cls, static_id)].append(feature)

            return static_id

        # Extract features
        feature = extract_features(crop, reid_model, device)

        # Check for matching players using average features
        best_match = None
        max_sim = 0

        # First check all known players of the same class
        for static_id in list(self.last_seen.keys()):
            avg_feature = self.get_avg_feature(static_id, cls)
            if avg_feature is not None:
                sim = cosine_similarity([feature], [avg_feature])[0][0]
                if sim > max_sim and sim > self.similarity_threshold:
                    max_sim = sim
                    best_match = static_id

        if best_match:
            self.assigned_ids[track_id] = best_match
            self.last_seen[best_match] = self.current_frame
            self.feature_db[(cls, best_match)].append(feature)
            return best_match

        # Assign new ID from available pool
        if self.available_ids[cls]:
            new_id = self.available_ids[cls].popleft()
            self.assigned_ids[track_id] = new_id
            self.last_seen[new_id] = self.current_frame
            self.feature_db[(cls, new_id)].append(feature)
            return new_id

        return None

    def cleanup(self):
        """Recycle IDs of players not seen recently"""
        for cls in [TEAM_A['class_id'], TEAM_B['class_id']]:
            for static_id in list(self.last_seen.keys()):
                if (self.current_frame - self.last_seen[static_id] > self.max_frames_missing and
                        static_id in self.available_ids[cls]):
                    self.available_ids[cls].append(static_id)
                    del self.last_seen[static_id]
                    # Remove from assigned_ids
                    for tid, sid in list(self.assigned_ids.items()):
                        if sid == static_id:
                            del self.assigned_ids[tid]

    def record_speed(self, static_id, speed):
        """Record speed data for analytics"""
        self.speed_data[static_id].append(speed)

    def record_position(self, static_id, position):
        """Record position for heatmap"""
        self.position_data[static_id].append(position)

