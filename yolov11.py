# 🎨 Define color by class
def get_color_by_class(cls_id):
    colors = {
        0: (0, 255, 0),       # Team A - Green
        1: (255, 0, 0),       # Team B - Blue
        2: (0, 140, 255),     # Coach - Orange
        3: (128, 0, 128),     # Referee - Purple
        4: (0, 255, 255),     # Hoop - Yellow
        5: (0, 0, 255)        # Ball - Red
    }
    return colors.get(cls_id, (255, 255, 255))  # Default white

