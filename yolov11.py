class RobustPlayerTracker:
    def __init__(self):
        self.feature_db = defaultdict(lambda: deque(maxlen=20))
        self.assigned_ids = {}
        self.player_history = defaultdict(lambda: deque(maxlen=60))
        self.current_detections = {}  # Store current frame detections
        self.position_data = defaultdict(list)
        self.speed_data = defaultdict(list)

        self.available_ids = {
            TEAM_A['class_id']: deque(TEAM_A['id_range']),
            TEAM_B['class_id']: deque(TEAM_B['id_range'])
        }
        self.last_seen = {}
        self.current_frame = 0

        self.similarity_threshold = 0.88
        self.max_frames_missing = 90  # ~3 seconds at 30fps
        self.min_features = 3
        self.reid_interval = 5  # Re-identify every N frames

    def get_robust_features(self, crops):
        """Process multiple crops for better feature extraction"""
        batch = torch.stack([transform(Image.fromarray(crop[..., ::-1])) for crop in crops])
        with torch.no_grad():
            return reid_model(batch.to(device)).cpu().numpy()

    def update_tracks(self, detections):
        """Main tracking logic with enhanced matching"""
        self.current_frame += 1
        self.current_detections = {}
        active_ids = set()

        # Store current detections
        for track_id, box, cls, crop in detections:
            self.current_detections[track_id] = box

        # Process current frame detections
        for track_id, box, cls, crop in detections:
            # Existing track update
            if track_id in self.assigned_ids:
                static_id = self.assigned_ids[track_id]
                active_ids.add(static_id)
                self.last_seen[static_id] = self.current_frame

                # Update features periodically
                if self.current_frame % self.reid_interval == 0:
                    feature = extract_features(crop, reid_model, device)
                    self.feature_db[(cls, static_id)].append(feature)
                continue

            # New detection handling
            feature = extract_features(crop, reid_model, device)
            best_match = self.find_best_match(cls, feature)

            if best_match:
                self.assigned_ids[track_id] = best_match
                active_ids.add(best_match)
                self.feature_db[(cls, best_match)].append(feature)
            else:
                self.assign_new_id(track_id, cls, feature)

        self.cleanup_tracks(active_ids)

    def find_best_match(self, cls, feature):
        """Enhanced matching with spatial consistency"""
        best_match = None
        max_sim = 0

        for (c, static_id), features in self.feature_db.items():
            if c == cls and len(features) >= self.min_features:
                avg_feature = np.mean(list(features)[-self.min_features:], axis=0)
                sim = cosine_similarity([feature], [avg_feature])[0][0]

                if sim > max_sim and sim > self.similarity_threshold:
                    max_sim = sim
                    best_match = static_id

        return best_match

    def assign_new_id(self, track_id, cls, feature):
        """Handle new player appearances"""
        if self.available_ids[cls]:
            new_id = self.available_ids[cls].popleft()
            self.assigned_ids[track_id] = new_id
            self.last_seen[new_id] = self.current_frame
            self.feature_db[(cls, new_id)].append(feature)

    def cleanup_tracks(self, active_ids):
        """Manage track lifecycle with hysteresis"""
        for cls in [TEAM_A['class_id'], TEAM_B['class_id']]:
            for static_id in list(self.last_seen.keys()):
                frames_missing = self.current_frame - self.last_seen[static_id]

                if (frames_missing > self.max_frames_missing and
                    static_id not in active_ids and
                    static_id in self.available_ids[cls]):

                    self.available_ids[cls].append(static_id)
                    del self.last_seen[static_id]

                    # Cleanup related data
                    for tid, sid in list(self.assigned_ids.items()):
                        if sid == static_id:
                            del self.assigned_ids[tid]

